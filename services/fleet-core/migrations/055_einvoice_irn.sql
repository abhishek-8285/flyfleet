-- Function to generate IRN hash (simplified - actual implementation uses NIC API)
CREATE OR REPLACE FUNCTION generate_irn_hash(
    p_invoice_no VARCHAR,
    p_fin_year VARCHAR,
    p_gstin VARCHAR,
    p_inv_type VARCHAR,
    p_inv_value DECIMAL
) RETURNS VARCHAR AS $$
DECLARE
    v_input TEXT;
    v_hash TEXT;
BEGIN
    -- IRN is SHA-256 hash of: InvoiceNo|FinYear|GSTIN|InvType|InvValue
    v_input := p_invoice_no || '|' || p_fin_year || '|' || p_gstin || '|' || p_inv_type || '|' || p_inv_value::TEXT;
    
    -- In production, use actual SHA-256 via extension or external service
    -- For now, return a placeholder
    v_hash := encode(sha256(v_input::bytea), 'hex');
    
    RETURN v_hash;
END;
$$ LANGUAGE plpgsql;

-- Function to check if e-invoice is mandatory
CREATE OR REPLACE FUNCTION is_einvoice_mandatory(
    p_org_id UUID,
    p_amount DECIMAL
) RETURNS BOOLEAN AS $$
DECLARE
    v_mandatory_above DECIMAL;
    v_enabled BOOLEAN;
BEGIN
    -- Get org configuration
    SELECT mandatory_above, is_enabled INTO v_mandatory_above, v_enabled
    FROM einvoice_config
    WHERE org_id = p_org_id AND is_active = true;
    
    -- If not enabled, return false
    IF NOT v_enabled THEN
        RETURN false;
    END IF;
    
    -- Check if amount is above threshold
    RETURN p_amount > v_mandatory_above;
END;
$$ LANGUAGE plpgsql;

-- View for e-invoice compliance status
CREATE OR REPLACE VIEW einvoice_compliance_status AS
SELECT 
    i.id as invoice_id,
    i.invoice_no,
    i.org_id,
    i.total_amount,
    ei.irn,
    ei.irn_status,
    ei.ack_no,
    ei.created_at as irn_created_at,
    CASE 
        WHEN ei.irn_status = 'generated' THEN 'Compliant'
        WHEN ei.irn_status = 'pending' THEN 'Pending'
        WHEN ei.irn_status = 'failed' THEN 'Failed'
        WHEN is_einvoice_mandatory(i.org_id, i.total_amount) THEN 'Non-Compliant'
        ELSE 'Not Required'
    END as compliance_status
FROM invoices i
LEFT JOIN einvoice_irn ei ON i.id = ei.invoice_id
WHERE i.deleted_at IS NULL;
