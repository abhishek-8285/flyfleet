-- Create e-invoice IRN table
CREATE TABLE IF NOT EXISTS einvoice_irn (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    invoice_id UUID NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
    org_id UUID NOT NULL,
    
    -- IRN details
    irn VARCHAR(64) UNIQUE, -- 64-character hash
    irn_status VARCHAR(20) DEFAULT 'pending', -- pending, generated, cancelled, failed
    
    -- NIC response
    ack_no VARCHAR(100), -- Acknowledgement number
    ack_dt TIMESTAMPTZ, -- Acknowledgement date/time
    signed_response TEXT, -- Signed JSON response from NIC
    
    -- QR code
    qr_code_str TEXT, -- QR code string
    qr_code_image BYTEA, -- QR code image (PNG)
    
    -- Cancellation
    cancelled BOOLEAN DEFAULT false,
    cancelled_at TIMESTAMPTZ,
    cancellation_reason TEXT,
    
    -- Retry logic
    retry_count INTEGER DEFAULT 0,
    last_retry_at TIMESTAMPTZ,
    error_message TEXT,
    
    -- Audit
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    created_by UUID,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_by UUID,
    
    -- Constraints
    CONSTRAINT chk_einvoice_retry_count CHECK (retry_count >= 0 AND retry_count <= 5)
);

-- Create e-invoice configuration table
CREATE TABLE IF NOT EXISTS einvoice_config (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id UUID NOT NULL UNIQUE,
    
    -- NIC credentials
    app_key VARCHAR(255), -- API key from NIC
    secret_key VARCHAR(255), -- Secret key
    username VARCHAR(100), -- GST portal username
    password VARCHAR(255), -- GST portal password
    
    -- Configuration
    is_enabled BOOLEAN DEFAULT false,
    environment VARCHAR(20) DEFAULT 'sandbox', -- sandbox, production
    gstin VARCHAR(15), -- GSTIN of the organization
    
    -- Thresholds
    mandatory_above DECIMAL(12, 2) DEFAULT 50000, -- Mandatory e-invoicing above this amount
    
    -- Status
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    
    CONSTRAINT chk_einvoice_gstin CHECK (gstin IS NULL OR LENGTH(gstin) = 15)
);

-- Create e-invoice item mapping table
CREATE TABLE IF NOT EXISTS einvoice_item_mapping (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id UUID NOT NULL,
    
    -- Product mapping
    product_id UUID,
    hsn_code VARCHAR(20) NOT NULL,
    sac_code VARCHAR(20),
    
    -- NIC mapping
    nic_code VARCHAR(20),
    gst_rate DECIMAL(5, 2),
    exemption_reason TEXT,
    
    -- Status
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    
    UNIQUE(org_id, hsn_code)
);

-- Indexes
