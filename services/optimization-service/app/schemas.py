from datetime import datetime
from typing import Optional, List, Dict, Any
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

class ErrorDetail(BaseModel):
    """Specific validation error details."""
    field: str
    code: str
    message: str

class ProblemDetails(BaseModel):
    """RFC 7807 Problem Details Response Body."""
    type: str = Field(..., description="URI reference identifying the problem type.")
    title: str = Field(..., description="Short, human-readable summary of the problem type.")
    status: int = Field(..., description="HTTP status code generated by the origin server.")
    detail: str = Field(..., description="Human-readable explanation specific to this occurrence of the problem.")
    instance: str = Field(..., description="URI reference that identifies the specific occurrence of the problem.")
    timestamp: datetime = Field(default_factory=datetime.utcnow, description="Timestamp of when the error occurred.")
    request_id: str = Field(..., description="Correlation ID for tracing.")
    errors: Optional[List[ErrorDetail]] = Field(None, description="Detailed validation errors (optional).")
    
    # Allow extra fields for extension
    model_config = ConfigDict(extra='allow')
