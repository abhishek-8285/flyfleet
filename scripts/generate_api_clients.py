#!/usr/bin/env python3
"""Generate deterministic API client artifacts from canonical OpenAPI spec.

Outputs:
- apps/dashboard-web/src/generated/api/operations.ts
- apps/dashboard-web/src/generated/api/contract.json
- apps/mobile/shared/generated/api_contract.json
- apps/mobile/shared/generated/openapi.sha256
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

import yaml

SPEC_PATH = Path("docs/api/openapi.yaml")
WEB_DIR = Path("apps/dashboard-web/src/generated/api")
MOBILE_DIR = Path("apps/mobile/shared/generated")

HTTP_METHODS = ["get", "post", "put", "patch", "delete", "options", "head"]


def sanitize_const(name: str) -> str:
    name = re.sub(r"[^a-zA-Z0-9]+", "_", name)
    name = re.sub(r"_+", "_", name).strip("_")
    return name.upper() or "OP"


def load_spec() -> dict:
    if not SPEC_PATH.exists():
        raise FileNotFoundError(f"missing spec: {SPEC_PATH}")
    with SPEC_PATH.open("r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def _compact_schema(schema: dict | None) -> dict:
    if not isinstance(schema, dict):
        return {}
    out: dict = {}
    for key in ("type", "format", "minimum", "maximum", "default", "pattern"):
        if key in schema:
            out[key] = schema[key]
    if "enum" in schema and isinstance(schema["enum"], list):
        out["enum"] = schema["enum"]
    return out


def _collect_parameters(path_item: dict, op: dict) -> list[dict]:
    merged: dict[tuple[str, str], dict] = {}
    for src in (path_item.get("parameters", []), op.get("parameters", [])):
        if not isinstance(src, list):
            continue
        for p in src:
            if not isinstance(p, dict):
                continue
            name = str(p.get("name", "")).strip()
            location = str(p.get("in", "")).strip()
            if not name or not location:
                continue
            merged[(name, location)] = {
                "name": name,
                "in": location,
                "required": bool(p.get("required", False)),
                "schema": _compact_schema(p.get("schema")),
            }
    return [merged[k] for k in sorted(merged.keys())]


def collect_operations(spec: dict) -> list[dict]:
    paths = spec.get("paths", {})
    ops: list[dict] = []
    for path in sorted(paths.keys()):
        item = paths[path] or {}
        for method in HTTP_METHODS:
            op = item.get(method)
            if not op:
                continue
            op_id = op.get("operationId")
            if not op_id:
                op_id = sanitize_const(f"{method}_{path}").lower()
            ops.append(
                {
                    "operationId": op_id,
                    "method": method.upper(),
                    "path": path,
                    "summary": op.get("summary", ""),
                    "tags": op.get("tags", []),
                    "parameters": _collect_parameters(item, op),
                    "requestBody": op.get("requestBody"),
                    "responses": op.get("responses", {}),
                }
            )
    return ops


def render_operations_kotlin(ops: list[dict], version: str) -> str:
    lines: list[str] = []
    lines.append("package com.flyfleet.vehicledevice.data.api")
    lines.append("")
    lines.append("import retrofit2.Response")
    lines.append("import retrofit2.http.*")
    lines.append("")
    lines.append("/**")
    lines.append(" * Auto-generated by scripts/generate_api_clients.py. DO NOT EDIT.")
    lines.append(f" * Source: {SPEC_PATH} (version {version})")
    lines.append(" */")
    lines.append("interface DeviceApiService {")
    lines.append("")
    for op in ops:
        method = op["method"]
        path = op["path"]
        op_id = op["operationId"]
        
        # Simple heuristic: only include endpoints relevant to device (starting with /device, /telemetry, /media, /forensics, /driver, /firmware)
        # Note: In a real enterprise app, we might split specs or use tags, but for this monorepo we filter here.
        if not any(path.startswith(p) for p in ["/device", "/telemetry", "/media", "/forensics", "/driver", "/firmware", "/auth"]):
            continue

        lines.append(f"    @ {method}(\"{path}\")")
        
        # Build parameter list
        params = []
        for p in op["parameters"]:
            p_name = p["name"]
            p_in = p["in"]
            if p_in == "path":
                params.append(f"@Path(\"{p_name}\") {p_name}: String")
            elif p_in == "query":
                params.append(f"@Query(\"{p_name}\") {p_name}: String?")
        
        # Handle body for POST/PUT/PATCH
        body_type = "Any"
        if method in ["POST", "PUT", "PATCH"] and op.get("requestBody"):
            content = op["requestBody"].get("content", {})
            json_content = content.get("application/json", {})
            schema = json_content.get("schema", {})
            if "$ref" in schema:
                body_type = schema["$ref"].split("/")[-1]
        
        if method in ["POST", "PUT", "PATCH"]:
            params.append(f"@Body request: {body_type}")

        # Handle response type
        resp_type = "Any"
        ok_resp = op.get("responses", {}).get("200") or op.get("responses", {}).get("201")
        if ok_resp:
            content = ok_resp.get("content", {})
            json_content = content.get("application/json", {})
            schema = json_content.get("schema", {})
            if "$ref" in schema:
                resp_type = schema["$ref"].split("/")[-1]
            elif schema.get("type") == "array":
                items = schema.get("items", {})
                if "$ref" in items:
                    resp_type = f"List<{items['$ref'].split('/')[-1]}>"

        param_str = ", ".join(params)
        lines.append(f"    suspend fun {op_id}({param_str}): Response<{resp_type}>")
        lines.append("")
    
    lines.append("}")
    return "\n".join(lines)


def render_operations_ts(ops: list[dict], version: str) -> str:
    lines: list[str] = []
    lines.append("/* eslint-disable */")
    lines.append("// Auto-generated by scripts/generate_api_clients.py. DO NOT EDIT.")
    lines.append(f"// Source: {SPEC_PATH} (version {version})")
    lines.append("")
    lines.append("export type HttpMethod = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE' | 'OPTIONS' | 'HEAD';")
    lines.append("")
    lines.append("export interface ApiOperation {")
    lines.append("  operationId: string;")
    lines.append("  method: HttpMethod;")
    lines.append("  path: string;")
    lines.append("  summary: string;")
    lines.append("  tags: string[];")
    lines.append("  parameters: {")
    lines.append("    name: string;")
    lines.append("    in: string;")
    lines.append("    required: boolean;")
    lines.append("    schema: Record<string, unknown>;")
    lines.append("  }[];")
    lines.append("}")
    lines.append("")
    lines.append("export const API_OPERATIONS: ApiOperation[] = [")
    for op in ops:
        lines.append(
            "  { "
            f"operationId: {json.dumps(op['operationId'])}, "
            f"method: {json.dumps(op['method'])} as HttpMethod, "
            f"path: {json.dumps(op['path'])}, "
            f"summary: {json.dumps(op['summary'])}, "
            f"tags: {json.dumps(op['tags'])}, "
            f"parameters: {json.dumps(op['parameters'])} "
            "},"
        )
    lines.append("];")
    lines.append("")
    lines.append("export class GeneratedApiClient {")
    lines.append("  constructor(private readonly baseUrl = '/api/v1') {}")
    lines.append("")
    lines.append("  async request<T>(method: HttpMethod, path: string, init: RequestInit = {}): Promise<T> {")
    lines.append("    const res = await fetch(`${this.baseUrl}${path}`, { ...init, method });")
    lines.append("    if (!res.ok) {")
    lines.append("      throw new Error(`API request failed: ${method} ${path} -> ${res.status}`);")
    lines.append("    }")
    lines.append("    return (await res.json()) as T;")
    lines.append("  }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def write_outputs(spec: dict, ops: list[dict]) -> None:
    WEB_DIR.mkdir(parents=True, exist_ok=True)
    MOBILE_DIR.mkdir(parents=True, exist_ok=True)

    version = str(((spec.get("info") or {}).get("version")) or "unknown")
    spec_sha = hashlib.sha256(SPEC_PATH.read_bytes()).hexdigest()

    web_ts = render_operations_ts(ops, version)
    (WEB_DIR / "operations.ts").write_text(web_ts, encoding="utf-8")

    kotlin_api = render_operations_kotlin(ops, version)
    kotlin_dir = Path("apps/mobile/vehicle-device/android-device/data/src/main/kotlin/com/flyfleet/vehicledevice/data/api")
    kotlin_dir.mkdir(parents=True, exist_ok=True)
    (kotlin_dir / "GeneratedDeviceApiService.kt").write_text(kotlin_api, encoding="utf-8")

    contract_payload = {
        "source": str(SPEC_PATH),
        "spec_version": version,
        "spec_sha256": spec_sha,
        "operation_count": len(ops),
        "operations": ops,
    }

    (WEB_DIR / "contract.json").write_text(
        json.dumps(contract_payload, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )

    (MOBILE_DIR / "api_contract.json").write_text(
        json.dumps(contract_payload, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )

    (MOBILE_DIR / "openapi.sha256").write_text(spec_sha + "\n", encoding="utf-8")

    readme = """# Generated API Artifacts

Generated from `docs/api/openapi.yaml` by `scripts/generate_api_clients.py`.
Do not edit these files manually.
"""
    (WEB_DIR / "README.md").write_text(readme, encoding="utf-8")
    (MOBILE_DIR / "README.md").write_text(readme, encoding="utf-8")

    print(f"spec_version={version}")
    print(f"spec_sha256={spec_sha}")
    print(f"operations_generated={len(ops)}")


def main() -> int:
    try:
        spec = load_spec()
        ops = collect_operations(spec)
        write_outputs(spec, ops)
    except Exception as exc:
        print(f"generate_api_clients=FAIL: {exc}")
        return 1

    print("generate_api_clients=PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
